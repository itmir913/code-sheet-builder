/* 이 앱은 문자열을 이어 붙여 HTML을 만드는 곳이 많다(문제 카드, 인쇄 화면,
 * 마스크 렌더링). 사용자가 입력한 제목·설명·코드가 그대로 들어가므로, 삽입 전에
 * 반드시 이 함수를 거쳐야 한다. */
export function esc(str) {
    if (!str) return '';
    return str
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#039;');
}
